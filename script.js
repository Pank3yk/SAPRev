const $ = (id) => document.getElementById(id);
const moduleSelect = $("moduleSelect");
const questionCount = $("questionCount");
const setup = $("setup"), quizPanel = $("quizPanel"), resultPanel = $("resultPanel");
let quiz = [], index = 0, score = 0, answeredCount = 0, answerLog = [], locked = false;

const modules = [...new Set(QUESTION_BANK.map(q => q.module))];
modules.forEach(module => {
  const opt = document.createElement("option");
  opt.value = module; opt.textContent = module;
  moduleSelect.appendChild(opt);
});
$("moduleCounts").innerHTML = modules.map(m =>
  `<span class="module-chip">${m}: ${QUESTION_BANK.filter(q => q.module === m).length}</span>`
).join("");

function shuffle(items) {
  const copy = [...items];
  for (let i = copy.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [copy[i], copy[j]] = [copy[j], copy[i]];
  }
  return copy;
}

function beginQuiz(source = null) {
  const selectedModule = moduleSelect.value;
  let pool = source || QUESTION_BANK.filter(q => selectedModule === "all" || q.module === selectedModule);
  if (!source && questionCount.value !== "all") pool = shuffle(pool).slice(0, Number(questionCount.value));
  quiz = [...pool];
  index = 0; score = 0; answeredCount = 0; answerLog = [];
  setup.classList.add("d-none");
  resultPanel.classList.add("d-none");
  quizPanel.classList.remove("d-none");
  renderQuestion();
}

function renderQuestion() {
  locked = false;
  const q = quiz[index];
  $("moduleLabel").textContent = q.module;
  $("questionNumber").textContent = index + 1;
  $("totalQuestions").textContent = quiz.length;
  $("score").textContent = score;
  $("answered").textContent = answeredCount;
  $("questionText").textContent = q.question;
  $("progressBar").style.width = `${(index / quiz.length) * 100}%`;
  $("feedback").className = "feedback mt-3 d-none";
  $("feedback").textContent = "";
  $("nextBtn").disabled = true;
  $("nextBtn").textContent = index === quiz.length - 1 ? "See results" : "Next question";
  const wrap = $("options");
  wrap.innerHTML = "";
  q.options.forEach((option, i) => {
    const btn = document.createElement("button");
    btn.type = "button";
    btn.className = "option-btn";
    btn.textContent = `${String.fromCharCode(65 + i)}. ${option}`;
    btn.addEventListener("click", () => chooseAnswer(i));
    wrap.appendChild(btn);
  });
}

function chooseAnswer(choice) {
  if (locked) return;
  locked = true;
  const q = quiz[index];
  const buttons = [...$("options").querySelectorAll("button")];
  buttons.forEach((btn, i) => {
    btn.disabled = true;
    if (q.answer !== null && i === q.answer) btn.classList.add("correct");
    if (i === choice && q.answer !== null && i !== q.answer) btn.classList.add("wrong");
  });
  answeredCount++;
  const feedback = $("feedback");
  feedback.classList.remove("d-none");
  if (q.answer === null) {
    feedback.classList.add("notice");
    feedback.innerHTML = `<strong>Answer key needs confirmation.</strong><br>${q.note || "This question has no confirmed answer key."}`;
    answerLog.push({q, choice, correct: false, unkeyed: true});
  } else if (choice === q.answer) {
    score++;
    feedback.classList.add("good");
    feedback.innerHTML = `<strong>Correct!</strong> The answer is <strong>${q.options[q.answer]}</strong>.`;
    answerLog.push({q, choice, correct: true, unkeyed: false});
  } else {
    feedback.classList.add("bad");
    feedback.innerHTML = `<strong>Incorrect.</strong> Correct answer: <strong>${q.options[q.answer]}</strong>.`;
    answerLog.push({q, choice, correct: false, unkeyed: false});
  }
  $("score").textContent = score;
  $("answered").textContent = answeredCount;
  $("progressBar").style.width = `${(answeredCount / quiz.length) * 100}%`;
  $("nextBtn").disabled = false;
}

function showResults() {
  quizPanel.classList.add("d-none");
  resultPanel.classList.remove("d-none");
  const keyedTotal = quiz.filter(q => q.answer !== null).length;
  $("finalScore").textContent = `${score} / ${keyedTotal}`;
  const pct = keyedTotal ? Math.round(score / keyedTotal * 100) : 0;
  $("resultMessage").textContent = `You answered ${score} of ${keyedTotal} keyed questions correctly (${pct}%). ${quiz.length - keyedTotal} question(s) had no confirmed answer key and were excluded from the percentage.`;
  $("reviewList").innerHTML = answerLog.map((entry, i) => {
    const status = entry.unkeyed ? "Needs answer-key confirmation" : entry.correct ? "Correct" : "Incorrect";
    const correctText = entry.q.answer === null ? (entry.q.note || "No answer key supplied.") : `Correct answer: ${entry.q.options[entry.q.answer]}`;
    return `<div class="review-item"><div class="d-flex justify-content-between gap-2"><strong>Q${i+1} · ${entry.q.module}</strong><span>${status}</span></div><div class="mt-1">${escapeHtml(entry.q.question)}</div><div class="small text-light-emphasis mt-1">${escapeHtml(correctText)}</div></div>`;
  }).join("");
}

function escapeHtml(value) {
  return String(value).replace(/[&<>"']/g, ch => ({"&":"&amp;","<":"&lt;",">":"&gt;",'"':"&quot;","'":"&#39;"}[ch]));
}

$("startBtn").addEventListener("click", () => beginQuiz());
$("nextBtn").addEventListener("click", () => {
  if (index < quiz.length - 1) { index++; renderQuestion(); }
  else showResults();
});
$("quitBtn").addEventListener("click", showResults);
$("restartBtn").addEventListener("click", () => {
  resultPanel.classList.add("d-none"); setup.classList.remove("d-none");
});
$("retryWrongBtn").addEventListener("click", () => {
  const retry = answerLog.filter(x => !x.correct).map(x => x.q);
  if (!retry.length) { alert("No incorrect or unkeyed questions to retry."); return; }
  beginQuiz(retry);
});
